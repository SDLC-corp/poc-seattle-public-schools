// Generates SAMPLE users → data/users.json. Names are fictional; one sample principal per
// real school (linked by school id). Deterministic, so re-running gives the same data.
// Usage: npm run generate:users   (overwrites any users added through the app)
import { readFile, writeFile } from 'node:fs/promises';

const SCHOOLS_FILE = new URL('../data/schools.json', import.meta.url);
const OUT_FILE = new URL('../data/users.json', import.meta.url);

const FIRST = ['Avery', 'Jordan', 'Morgan', 'Riley', 'Casey', 'Taylor', 'Quinn', 'Rowan', 'Harper', 'Emerson',
  'Logan', 'Parker', 'Reese', 'Sawyer', 'Hayden', 'Dakota', 'Kendall', 'Skyler', 'Finley', 'Marlow',
  'Elena', 'Marcus', 'Priya', 'Tomas', 'Grace', 'Daniel', 'Aisha', 'Samuel', 'Leah', 'Victor',
  'Nora', 'Isaac', 'Mei', 'Oscar', 'Hana', 'Felix', 'Ines', 'Theo', 'Ruth', 'Andre'];
const LAST = ['Alder', 'Birch', 'Calloway', 'Dunmore', 'Easton', 'Fairbanks', 'Garrison', 'Holloway', 'Ingram',
  'Jessup', 'Kensington', 'Lockhart', 'Merriweather', 'Northcott', 'Oakley', 'Pemberton', 'Quill', 'Radcliffe',
  'Sterling', 'Thornbury', 'Underwood', 'Vance', 'Whitlock', 'Yardley', 'Ashford', 'Blackwood', 'Crane',
  'Delacroix', 'Ellery', 'Fenwick'];

function rng(seedText) {
  let seed = 0;
  for (const ch of seedText) seed = (Math.imul(seed, 31) + ch.charCodeAt(0)) >>> 0;
  return () => {
    seed = (seed + 0x6d2b79f5) >>> 0;
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = rng('sps-users');
const pick = (list) => list[Math.floor(rand() * list.length)];
const usedNames = new Set();

function uniqueName() {
  for (;;) {
    const name = `${pick(FIRST)} ${pick(LAST)}`;
    if (!usedNames.has(name)) {
      usedNames.add(name);
      return name;
    }
  }
}

const NOW = Date.parse('2026-11-01T17:00:00Z');
const daysAgo = (min, max) => new Date(NOW - (min + rand() * (max - min)) * 86400000).toISOString();
const phone = () => `(206) 555-${String(1000 + Math.floor(rand() * 9000))}`;

function makeUser(roleId, { domain = 'seattleschools.org', department, jobTitle, access, inactiveChance = 0.03 }) {
  const name = uniqueName();
  const [first, last] = name.toLowerCase().split(' ');
  const createdAt = daysAgo(120, 900);
  const inactive = rand() < inactiveChance;
  return {
    name,
    email: `${first}.${last}@${domain}`,
    phone: phone(),
    department,
    jobTitle,
    roleId,
    access,
    status: inactive ? 'inactive' : 'active',
    lastLogin: inactive ? daysAgo(60, 200) : daysAgo(0, 14),
    createdAt,
  };
}

async function main() {
  const { schools } = JSON.parse(await readFile(SCHOOLS_FILE, 'utf8'));
  const ids = schools.map((s) => s.id);
  const someSchools = (n) => [...ids].sort(() => rand() - 0.5).slice(0, n);

  const users = [
    makeUser('ehs-manager', { department: 'Environmental Health & Safety', jobTitle: 'EHS Manager', access: { scope: 'all', schoolIds: [] }, inactiveChance: 0 }),
    makeUser('ehs-manager', { department: 'Environmental Health & Safety', jobTitle: 'EHS Program Coordinator', access: { scope: 'all', schoolIds: [] }, inactiveChance: 0 }),
    ...schools.map((s) => makeUser('principal', {
      department: s.name, jobTitle: 'Principal', access: { scope: 'schools', schoolIds: [s.id] },
    })),
    ...Array.from({ length: 8 }, () => makeUser('facilities-manager', {
      department: 'Facilities Operations', jobTitle: 'Facilities Manager', access: { scope: 'schools', schoolIds: someSchools(10) },
    })),
    ...Array.from({ length: 6 }, () => makeUser('inspector', {
      department: 'Environmental Health & Safety', jobTitle: 'AHERA Inspector', access: { scope: 'schools', schoolIds: someSchools(15) },
    })),
    ...Array.from({ length: 2 }, () => makeUser('capital-projects', {
      department: 'Capital Projects & Planning', jobTitle: 'Project Manager', access: { scope: 'all', schoolIds: [] },
    })),
    ...Array.from({ length: 4 }, () => makeUser('contractor', {
      domain: 'abatement-contractor.example', department: 'External Contractor', jobTitle: 'Abatement Supervisor',
      access: { scope: 'assigned', schoolIds: someSchools(3) }, inactiveChance: 0.25,
    })),
    ...Array.from({ length: 2 }, () => makeUser('lab-user', {
      domain: 'analytical-lab.example', department: 'External Laboratory', jobTitle: 'Lab Analyst',
      access: { scope: 'lab', schoolIds: [] },
    })),
  ].map((u, i) => ({ id: `u${String(i + 1).padStart(3, '0')}`, ...u }));

  await writeFile(OUT_FILE, JSON.stringify({
    note: 'SAMPLE DATA — fictional users generated by scripts/generate-users.js',
    users,
  }, null, 2));
  console.log(`Wrote ${users.length} sample users to data/users.json`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
